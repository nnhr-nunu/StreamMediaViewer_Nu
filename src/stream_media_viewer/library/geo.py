@lru_cache(maxsize=1)
def _arrays() -> tuple[list[float], list[float], list[str]]:
    lats = [row[0] for row in _PLACES]
    lons = [row[1] for row in _PLACES]
    names = [row[2] for row in _PLACES]
    return lats, lons, names


def gps_to_decimal(dms: object, ref: str) -> float | None:
    if not isinstance(dms, (list, tuple)) or len(dms) < 3:
        return None
    parts: list[float] = []
    for item in dms[:3]:
        if hasattr(item, "numerator") and hasattr(item, "denominator"):
            denom = float(item.denominator or 1)
            parts.append(float(item.numerator) / denom)
        elif isinstance(item, (list, tuple)) and len(item) == 2:
            denom = float(item[1] or 1)
            parts.append(float(item[0]) / denom)
        else:
            try:
                parts.append(float(item))
            except (TypeError, ValueError):
                return None
    value = parts[0] + parts[1] / 60.0 + parts[2] / 3600.0
    if str(ref).upper() in {"S", "W"}:
        value = -value
    if not math.isfinite(value):
        return None
    return value


def place_from_gps(lat: float, lon: float) -> str:
    lats, lons, names = _arrays()
    best = ""
    best_km2 = 1e18
    cos_lat = math.cos(math.radians(lat))
    for index, plat in enumerate(lats):
        dy = (plat - lat) * 111.0
        dx = (lons[index] - lon) * 111.0 * cos_lat
        dist = dy * dy + dx * dx
        if dist < best_km2:
            best_km2 = dist
            best = names[index]
    # およそ 45km 以内の一番近い街だけ（遠い県庁所在地に寄せない）
    if best_km2 > 45.0 * 45.0:
        return ""
    return best
